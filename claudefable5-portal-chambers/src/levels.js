// 五间测试室数据 — 所有几何为轴对齐盒 {min,max,mat}
// mat: 'white'(可放传送门) | 'dark' | 'floor' | 'ceil' | 'metal'
// 弹道校核(g=16):走入深坑时眼睛下落 ≈6.5m → 门面处速度 ≈14.4 m/s;
// 高墙门中心 y∈[5.6,7.8] 时落点 z ∈ [−3.0,−4.6],全面板带越过 4.5m 裂谷。
// 防作弊:普通跳跃有效距离 = 中心跳距 3.0m + AABB 半宽 0.64 + 土狼 0.4 ≈ 4.04m < 4.5m,
// 且台阶助爬仅限着地状态(空中无救援),裂谷双向都跳不过去。
const B = (min, max, mat) => ({ min, max, mat });

// Z 向墙开门洞:返回洞口周围的墙块(左/右/上)
function wallZHole(x0, x1, y0, y1, z0, z1, hx0, hx1, hy1, mat) {
  return [
    B([x0, y0, z0], [hx0, y1, z1], mat),
    B([hx1, y0, z0], [x1, y1, z1], mat),
    B([hx0, hy1, z0], [hx1, y1, z1], mat),
  ];
}
// X 向墙开门洞
function wallXHole(x0, x1, y0, y1, z0, z1, hz0, hz1, hy0, hy1, mat) {
  const parts = [
    B([x0, y0, z0], [x1, y1, hz0], mat),
    B([x0, y0, hz1], [x1, y1, z1], mat),
    B([x0, hy1, hz0], [x1, y1, hz1], mat),
  ];
  if (hy0 > y0) parts.push(B([x0, y0, hz0], [x1, hy0, hz1], mat));
  return parts;
}

