export function formatYear(year) {
  if (!Number.isFinite(year)) return '';
  const displayYear = Math.trunc(year);
  if (displayYear < 0) return `公元前${Math.abs(displayYear)}年`;
  if (displayYear === 0) return '公元纪年交界';
  if (displayYear === 1) return '公元元年';
  return `公元${displayYear}年`;
}

export function getCityNameAtYear(cityOrId, year) {
  const target = typeof cityOrId === 'string'
    ? CITIES.find((entry) => entry.id === cityOrId)
    : cityOrId;

  if (!target || !Number.isFinite(year) || year < target.founded) return null;

  const match = target.historicalNames.find((entry) => {
    const from = entry.from ?? target.founded;
    const to = entry.to ?? Number.POSITIVE_INFINITY;
    return year >= from && year <= to;
  });

  return match?.name ?? target.name;
}
