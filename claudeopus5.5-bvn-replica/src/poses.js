const sinD = (a) => Math.sin(a * Math.PI / 180);
// 待机呼吸(基于站姿)
export function idlePose(base, t) {
  const b = sinD(t * 6);
  return { ...base, t: base.t + b * 1.5, h: base.h - b * 1.2, a2: base.a2 + b * 4, b2: base.b2 + b * 4, f2: base.f2 + (b + 1) * 2, k2: base.k2 + (b + 1) * 2 };
}
// 走路循环
export function walkPose(base, ph, back) {
  const s = sinD(ph), c = sinD(ph + 90);
  const d = back ? -1 : 1;
  return {
    ...base,
    t: base.t + (back ? -4 : 3),
    f1: 12 + 26 * s * d, f2: 14 + 22 * Math.max(0, -c),
    k1: -12 - 26 * s * d, k2: 14 + 22 * Math.max(0, c),
    a1: base.a1 - 6 * s, b1: base.b1 + 6 * s,
  };
}
// 跑步循环(忍者跑:双臂后摆)
export function runPose(base, ph) {
  const s = sinD(ph), c = sinD(ph + 90);
  return { ...base, f1: 30 + 45 * s, f2: 30 + 60 * Math.max(0, -c), k1: 30 - 45 * s - 30, k2: 30 + 60 * Math.max(0, c) };
}
