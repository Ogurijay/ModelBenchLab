export function getBeaufortScale(windSpeed) {
  const thresholds = [0.3, 1.6, 3.4, 5.5, 8.0, 10.8, 13.9, 17.2, 20.8, 24.5, 28.5, 32.7];
  let level = 0;
  for (let i = 0; i < thresholds.length; i++) {
    if (windSpeed >= thresholds[i]) level = i + 1;
  }
  return level;
}
